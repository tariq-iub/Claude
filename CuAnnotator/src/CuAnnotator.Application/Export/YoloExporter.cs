using System.Globalization;
using System.Text;
using CuAnnotator.Domain.Entities;

namespace CuAnnotator.Application.Export;

public enum YoloHolePolicy
{
    /// <summary>Do not export annotations with holes (warn).</summary>
    Skip,
    /// <summary>Export only the outer boundary (warn: hole pixels become foreground).</summary>
    OuterBoundaryOnly,
}

/// <summary>
/// YOLO segmentation labels: one line per polygon, "<c>class x1 y1 x2 y2 …</c>" with xₙ = x / W, yₙ = y / H
/// using pixel-centre coordinates. YOLO class indices are contiguous from 0, mapped from taxonomy IDs in
/// ascending order (written to data.yaml). Limitations, all reported as warnings, never silent:
/// holes cannot be represented; each disconnected component becomes its own line (instance identity lost).
/// </summary>
public static class YoloExporter
{
    public static IReadOnlyDictionary<int, int> ClassIndexMap(Taxonomy taxonomy) =>
        taxonomy.Classes.Where(c => c.Id != Taxonomy.UnlabeledId && c.Id != Taxonomy.IgnoreId).OrderBy(c => c.Id)
            .Select((c, i) => (c.Id, i)).ToDictionary(t => t.Id, t => t.i);

    public static string LabelFile(ImageItem image, IReadOnlyDictionary<int, int> map, YoloHolePolicy holes, ExportReport report, string set = "default")
    {
        var sb = new StringBuilder();
        double W = image.Width, H = image.Height;
        foreach (var a in image.Annotations.Where(a => a.AnnotationSet == set).OrderBy(a => a.ZOrder))
        {
            if (!map.TryGetValue(a.ClassId, out int cls)) continue; // Ignore/Unlabeled
            if (a.Polygons.Any(p => p.Holes.Count > 0))
            {
                if (holes == YoloHolePolicy.Skip)
                {
                    report.Warn($"YOLO: {image.FileName} annotation {a.Id} has holes and was skipped (format cannot represent holes).");
                    continue;
                }
                report.Warn($"YOLO: {image.FileName} annotation {a.Id} exported without its holes ({a.Polygons.Sum(p => p.Holes.Count)} hole(s) filled).");
            }
            if (a.Polygons.Count > 1)
                report.Warn($"YOLO: {image.FileName} annotation {a.Id} has {a.Polygons.Count} disconnected parts, written as separate instances.");
            foreach (var p in a.Polygons)
            {
                if (p.Outer.Count < 3)
                {
                    report.Warn($"YOLO: {image.FileName} annotation {a.Id} has a component with {p.Outer.Count} vertex/vertices (sub-polygon), skipped.");
                    continue;
                }
                sb.Append(cls.ToString(CultureInfo.InvariantCulture));
                foreach (var v in p.Outer)
                    sb.Append(' ').Append(((v.X + 0.5) / W).ToString("0.######", CultureInfo.InvariantCulture))
                      .Append(' ').Append(((v.Y + 0.5) / H).ToString("0.######", CultureInfo.InvariantCulture));
                sb.Append('\n');
            }
        }
        return sb.ToString();
    }

    public static string DataYaml(Taxonomy taxonomy, string root)
    {
        var map = ClassIndexMap(taxonomy);
        var sb = new StringBuilder();
        sb.Append("# Generated by CuAnnotator. 'names' index → taxonomy class ID is given in comments.\n");
        sb.Append($"path: {root}\ntrain: yolo/images/train\nval: yolo/images/val\ntest: yolo/images/test\nnames:\n");
        foreach (var (id, idx) in map.OrderBy(k => k.Value))
            sb.Append($"  {idx}: \"{taxonomy.Get(id).Name}\"  # taxonomy id {id}\n");
        return sb.ToString();
    }
}

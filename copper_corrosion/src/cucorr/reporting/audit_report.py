"""Render the workbook audit as JSON, Markdown and figures."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw


def swatch_figure(classes: list[dict], path: Path) -> None:
    cell, pad = 60, 110
    im = Image.new("RGB", (pad + 4 * cell, len(classes) * cell), "white")
    d = ImageDraw.Draw(im)
    for r, c in enumerate(classes):
        d.text((6, r * cell + 22), f"{c['class_id']} {c['name']}", fill="black")
        for k, rgb in enumerate([c["rep_color"], *c["refs"]]):
            d.rectangle([pad + k * cell, r * cell + 4, pad + (k + 1) * cell - 4, (r + 1) * cell - 4], fill=tuple(rgb))
    im.save(path)


def write_audit(rep: dict, out: str | Path) -> None:
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "audit.json").write_text(json.dumps(rep, indent=1, default=str))
    swatch_figure(rep["classes"], out / "reference_swatches.png")
    m = rep["manifest"]
    L = ["# Input-data audit", "", "Generated by `python -m cucorr.cli audit`.", "", "## Workbooks", ""]
    for f, sheets in rep["sheets"].items():
        for s, info in sheets.items():
            L.append(f"- **{f} / {s}**: {info['shape'][0]} rows x {info['shape'][1]} cols; columns "
                     + ", ".join(f"`{c}` ({t})" for c, t in info["columns"].items())
                     + f"; missing values: {sum(info['missing'].values())}")
    L += ["", "## Classes and reference colours (settings.xlsx)", "", "![swatches](reference_swatches.png)", "",
          "| ID | Class | settings id | rep_color | ref1 | ref2 | ref3 |", "|---|---|---|---|---|---|---|"]
    for c in rep["classes"]:
        refs = c["refs"] + [None] * (3 - len(c["refs"]))
        L.append(f"| {c['class_id']} | {c['name']} | {c['settings_id']} | {tuple(c['rep_color'])} | "
                 + " | ".join(str(tuple(r)) if r else "missing" for r in refs) + " |")
    L += ["", "## Manifest (labels.xlsx)", "",
          f"- Rows: {m['rows']}; versions: {m['versions']}; cluster_id range {m['cluster_id_range']}, "
          f"{m['cluster_id_duplicates']} duplicates, {m['cluster_id_gaps']} gaps.",
          f"- Duplicate Lab rows: {m['duplicate_lab_rows']}; rows outside the sRGB gamut: {m['out_of_srgb_gamut_rows']}.",
          f"- Extra columns: {m['extra_columns']}.", f"- Class names compatible with settings.xlsx: "
          f"{rep['class_names_compatible']}.", "", "| Class | Clusters | mean L* | mean a* | mean b* |",
          "|---|---|---|---|---|"]
    for k, v in sorted(m["class_counts"].items(), key=lambda t: -t[1]):
        mu = m["per_class_lab_mean"][k]
        L.append(f"| {k} | {v} | {mu['lab_l']:.1f} | {mu['lab_a']:.1f} | {mu['lab_b']:.1f} |")
    cons = rep["consistency"]
    L += ["", "## Cross-file consistency", "",
          f"Nearest settings reference (CIEDE2000, D65) reproduces the manifest label for "
          f"**{cons['manifest_vs_settings_nearest_ref_agreement']:.1%}** of clusters.", "",
          "Rows = manifest label, columns = class of nearest settings reference colour:", ""]
    conf = cons["confusion"]; cols = sorted(conf); rows = sorted(next(iter(conf.values())))
    L += ["| manifest \\ nearest | " + " | ".join(cols) + " |", "|" + "---|" * (len(cols) + 1)]
    for r in rows:
        L.append(f"| {r} | " + " | ".join(str(conf[c].get(r, 0)) for c in cols) + " |")
    for sec in ("warnings", "assumptions", "unresolved"):
        L += ["", f"## {sec.capitalize()}", ""] + [f"- {w}" for w in rep[sec]]
    (out / "audit.md").write_text("\n".join(L) + "\n")
    _ = np
